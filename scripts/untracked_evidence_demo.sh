#!/usr/bin/env bash
# Negative test for the untracked-evidence rule across the host-only guards.
#
# Every guard that consumes evidence must refuse a file that exists only in
# the author's working tree, because a fresh checkout does not have it. This
# script creates an untracked copy, runs each guard against it, and requires
# the guard to fail with the "not tracked by git" message. Everything is
# removed on exit; nothing is committed.
#
# Cases:
#   perf_numbers     delegated to scripts/perf_numbers_untracked_demo.sh
#   claims           a cited location in docs/claims.json that is untracked
#   spec_drift       a parent spec file that is not committed
#   long_description the wheel long description that is not committed
#   conformance      the shared helper's verdict for a vector and its mirror
#
# Host-only: no Docker, no build, no network.
set -Eeuo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"

stamp="$(date -u +%Y%m%dT%H%M%SZ)"
work=".docker-cache/untracked-evidence-$stamp"
mkdir -p "$work"
failures=0

cleanup() { rm -rf "$work"; }
trap cleanup EXIT

pass() { printf 'PASS  %s\n' "$1"; }
fail() { printf 'FAIL  %s\n' "$1" >&2; failures=$((failures + 1)); }

# ---- perf_numbers --------------------------------------------------------
if bash scripts/perf_numbers_untracked_demo.sh >"$work/perf.out" 2>&1; then
  pass "perf_numbers refuses an untracked receipt"
else
  fail "perf_numbers accepted an untracked receipt"
  cat "$work/perf.out" >&2
fi

# ---- claims --------------------------------------------------------------
# A real claim that is present in README.md, re-pointed at an uncommitted copy
# of the same text: the content check passes, the tracked check must not.
cp README.md docs/$stamp-untracked-claim-location.md
entry="$(jq -c --arg loc "docs/$stamp-untracked-claim-location.md" \
  '[.[] | select(.kind == "present" and (.locations | index("README.md")) and ((.superseded_by // "") == ""))][0]
   | .locations = [$loc]' docs/claims.json)"
if [[ "$entry" == "null" || -z "$entry" ]]; then
  fail "claims demo could not find a README.md claim to re-point"
else
  jq -n --argjson e "$entry" '[$e]' > "$work/claims.json"
  set +e
  out="$(bash scripts/check-claims.sh "$work/claims.json" 2>&1)"
  rc=$?
  set -e
  if [[ "$rc" -eq 0 ]]; then
    fail "claims accepted an untracked location"
    printf '%s\n' "$out" >&2
  elif ! grep -Fq "an untracked file is not evidence" <<<"$out"; then
    fail "claims failed, but not for the tracked rule"
    printf '%s\n' "$out" >&2
  else
    pass "claims refuses an untracked location"
  fi
fi
rm -f docs/$stamp-untracked-claim-location.md

# ---- spec drift ----------------------------------------------------------
# A parent spec that exists, is byte-identical to nothing else (its mirror is
# absent, which is also a failure), and is not committed. The tracked rule must
# name it directly rather than relying on the missing-mirror report.
first_spec="$(find spec -maxdepth 1 -type f -name '*.md' | sort | head -1)"
if [[ -z "$first_spec" ]]; then
  fail "spec drift demo could not find a parent spec file"
else
  cp "$first_spec" "spec/ZZ-untracked-demo-$stamp.md"
  set +e
  out="$(bash scripts/check-spec-drift.sh 2>&1)"
  rc=$?
  set -e
  if [[ "$rc" -eq 0 ]]; then
    fail "spec drift accepted an untracked parent spec"
  elif ! grep -Fq "spec/ZZ-untracked-demo-$stamp.md is not tracked by git" <<<"$out"; then
    fail "spec drift failed, but not for the tracked rule"
    printf '%s\n' "$out" >&2
  else
    pass "spec drift refuses an untracked export"
  fi
  rm -f "spec/ZZ-untracked-demo-$stamp.md"
fi

# ---- long description ----------------------------------------------------
mkdir -p "$work/longdesc/python"
cp python/README.md "$work/longdesc/python/README.md"
set +e
out="$(python3 scripts/check_long_description.py --root "$work/longdesc" 2>&1)"
rc=$?
set -e
if [[ "$rc" -eq 0 ]]; then
  fail "long_description accepted an untracked python/README.md"
elif ! grep -Fq "is not tracked by git" <<<"$out"; then
  fail "long_description failed, but not for the tracked rule"
  printf '%s\n' "$out" >&2
else
  pass "long_description refuses an untracked target"
fi

# ---- conformance ---------------------------------------------------------
# The manifest is generated by walking the tree, so an untracked vector also
# makes `--check` report the manifest as stale (fail closed). This case pins
# the helper's verdict, which is what gives the precise message.
cp "$first_spec" "$work/nothing.txt" # ensure the work dir exists and is populated
python3 - "$work" <<'PY'
import os
import sys

sys.path.insert(0, os.path.join(os.getcwd(), "scripts"))
from tracked_evidence import TrackedEvidence

index = TrackedEvidence(os.getcwd())
tracked = "conformance/manifest.json"
untracked = os.path.join(sys.argv[1], "longdesc", "python", "README.md")
verdict_tracked = index.tracked(tracked)
verdict_untracked = index.tracked(untracked)
print("conformance/manifest.json tracked=%r" % (verdict_tracked,))
print("%s tracked=%r" % (untracked, verdict_untracked))
raise SystemExit(0 if verdict_tracked is True and verdict_untracked is False else 1)
PY
if [[ $? -eq 0 ]]; then
  pass "conformance helper distinguishes tracked from untracked evidence"
else
  fail "conformance helper verdict is wrong"
fi

if [[ "$failures" -ne 0 ]]; then
  printf 'untracked evidence demo: FAIL (%d case(s))\n' "$failures" >&2
  exit 1
fi
echo "untracked evidence demo: PASS (4 guards)"
